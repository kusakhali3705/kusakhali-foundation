-- Kusakhali Foundation database schema
-- Run this file in Supabase Dashboard > SQL Editor.
-- Never expose the service_role key in the browser.

create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text,
 role text not null default 'member' check (role in ('admin','member')),
 created_at timestamptz not null default now()
);
create table if not exists public.members (
 id bigint generated by default as identity primary key,
 serial int not null unique check (serial between 1 and 50),
 name text not null,
 mobile text,
 ward int check (ward between 1 and 9),
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.transactions (
 id bigint generated by default as identity primary key,
 date date not null,
 type text not null check (type in ('অনুদান','অন্যান্য আয়','ব্যয়','সহায়তা')),
 member_name text,
 ward int check (ward between 1 and 9),
 amount numeric(14,2) not null check (amount > 0),
 reason text,
 receipt text,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create table if not exists public.committee (
 id bigint generated by default as identity primary key,
 name text not null,
 ward int check (ward between 1 and 9),
 mobile text,
 position text not null,
 created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.members enable row level security;
alter table public.transactions enable row level security;
alter table public.committee enable row level security;

-- Profiles: authenticated users can see profiles; users can only update their own non-role fields.
drop policy if exists "profiles readable by authenticated" on public.profiles;
create policy "profiles readable by authenticated" on public.profiles for select to authenticated using (true);
-- No client-side UPDATE policy on profiles: a member must not be able to promote
-- their own account to admin. Change roles only from the Supabase SQL editor.

-- Members and committee are visible to logged-in members; only admins can change them.
drop policy if exists "members visible to authenticated" on public.members;
create policy "members visible to authenticated" on public.members for select to authenticated using (true);
drop policy if exists "members admin insert" on public.members;
create policy "members admin insert" on public.members for insert to authenticated with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
drop policy if exists "members admin update" on public.members;
create policy "members admin update" on public.members for update to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin')) with check (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));
drop policy if exists "members admin delete" on public.members;
create policy "members admin delete" on public.members for delete to authenticated using (exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

